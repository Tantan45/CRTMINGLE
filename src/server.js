require('dotenv').config();
const required = ['SESSION_SECRET','FINGERPRINT_SECRET','ADMIN_ACCESS_CODE_HASH'];
const missing = required.filter(key => !process.env[key] || process.env[key].includes('replace-with'));
if (missing.length) throw new Error(`Startup blocked. Configure: ${[...new Set(missing)].join(', ')}`);
if (process.env.SESSION_SECRET.length < 32 || process.env.FINGERPRINT_SECRET.length < 32) throw new Error('SESSION_SECRET and FINGERPRINT_SECRET must each contain at least 32 characters.');
if (!/^[a-f0-9]{64}$/i.test(process.env.ADMIN_ACCESS_CODE_HASH)) throw new Error('ADMIN_ACCESS_CODE_HASH must be generated with npm run admin:hash.');
const path=require('path');
const express=require('express');
const http=require('http');
const helmet=require('helmet');
const compression=require('compression');
const session=require('express-session');
const SQLiteStore=require('connect-sqlite3')(session);
const {Server}=require('socket.io');
const db=require('./db/database');
db.cleanupExpiredData();
const authRoutes=require('./routes/auth');
const studentRoutes=require('./routes/student');
const adminRoutes=require('./routes/admin');
const {attachChat}=require('./sockets/chat');
const app=express(),server=http.createServer(app);if(process.env.TRUST_PROXY==='true')app.set('trust proxy',1);
const io=new Server(server,{maxHttpBufferSize:10_000,serveClient:true});
app.set('io',io);
const sessionDir=process.env.VERCEL?'/tmp/crtmingle-sessions':path.resolve('./data');require('fs').mkdirSync(sessionDir,{recursive:true});
const sessionMiddleware=session({name:'crtmingle.sid',store:new SQLiteStore({db:'sessions.sqlite',dir:sessionDir}),secret:process.env.SESSION_SECRET||'development-secret-change-this-before-deploying',resave:false,saveUninitialized:false,cookie:{httpOnly:true,sameSite:'strict',secure:process.env.NODE_ENV==='production',maxAge:8*60*60_000}});
app.use(helmet({contentSecurityPolicy:{directives:{defaultSrc:["'self'"],scriptSrc:["'self'","https://cdn.socket.io"],styleSrc:["'self'","'unsafe-inline'"],imgSrc:["'self'","data:"],connectSrc:["'self'","ws:","wss:"]}}}));
app.use(compression());app.use(express.json({limit:'10kb'}));app.use(sessionMiddleware);io.engine.use(sessionMiddleware);
app.use('/api/auth',require('express-rate-limit').rateLimit({windowMs:15*60_000,limit:20,standardHeaders:true,legacyHeaders:false}));
app.use('/api/auth',authRoutes);app.use('/api/student',studentRoutes);app.use('/api/admin',adminRoutes);
// Serve the separate chat page and forward old demo bookmarks to it.
app.get('/chat',(req,res)=>res.sendFile(path.join(__dirname,'..','public','chat.html')));
app.get('/guest-demo.html',(req,res)=>res.redirect(302,'/chat'));
app.get('/api/public/config',(req,res)=>{res.set('Cache-Control','no-store');let telegramGroupUrl=null;try{const candidate=new URL(process.env.TELEGRAM_GROUP_URL||'');if(candidate.protocol==='https:')telegramGroupUrl=candidate.toString()}catch{}res.json({telegramGroupUrl,counselor:process.env.COUNSELOR_CONTACT||'Contact your school counselor through CRT student services.',crisis:process.env.CRISIS_RESOURCE||'Philippines NCMH Crisis Hotline: 1553',onlineUsers:new Set([...io.sockets.sockets.values()].map(socket=>socket.userId)).size})});
app.use(express.static(path.join(__dirname,'..','public')));
app.get('/admin',(req,res)=>res.sendFile(path.join(__dirname,'..','public','admin.html')));
app.get('/health',(req,res)=>res.json({ok:true}));
attachChat(io);
const retentionTimer=setInterval(()=>db.cleanupExpiredData(),6*60*60_000);retentionTimer.unref();
const port=Number(process.env.PORT||3000);server.listen(port,'0.0.0.0',()=>console.log(`CRTMINGLE listening on ${port}`));
